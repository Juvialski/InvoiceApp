/**
 * Pure payroll calendar projections.
 *
 * This module deliberately does not generate payroll periods from a schedule.
 * A calendar consumes the actual period records that were generated or imported
 * by the payroll domain. That keeps DAILY through CUSTOM schedules, including
 * cross-month and historical periods, visible without re-deriving them here.
 *
 * Date-only arithmetic uses UTC midnight. The only local-time operation is the
 * default "today" value, which uses the host's local calendar date rather than
 * UTC's date.
 */

import type { PayrollEntry, PayrollPeriod, PayrollRun } from "../types.ts";
import type { PayrollImportBatch } from "../lib/payrollImportPersistence.ts";

export type DateOnly = string;
export type PayrollFrequency = "DAILY" | "WEEKLY" | "BIWEEKLY" | "SEMI_MONTHLY" | "MONTHLY" | "CUSTOM";

export type CalendarPeriod = Pick<PayrollPeriod, "id" | "periodStart" | "periodEnd" | "payDate" | "status"> &
  Partial<Pick<PayrollPeriod, "scheduleId" | "scheduleVersionId" | "autoGenerated" | "lockedAt">>;

export type CalendarRun = Pick<PayrollRun, "id" | "periodId" | "status">;
export type CalendarEntry = Pick<PayrollEntry, "id" | "payrollRunId" | "calculationSnapshot">;

